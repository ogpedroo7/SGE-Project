import os
from threading import Lock

from psycopg.rows import dict_row
from psycopg_pool import ConnectionPool


_pool = None
_pool_lock = Lock()


def conectar_banco():
    """Obtém uma conexão reutilizável do pool PostgreSQL."""
    global _pool

    database_url = os.getenv("DATABASE_URL")
    if not database_url:
        raise RuntimeError(
            "A variável DATABASE_URL não foi configurada no ambiente."
        )

    # Cria o pool apenas quando a primeira requisição precisar do banco.
    # Assim, a importação do módulo não tenta conectar antes da configuração.
    if _pool is None:
        with _pool_lock:
            if _pool is None:
                _pool = ConnectionPool(
                    conninfo=database_url,
                    min_size=1,
                    max_size=5,
                    timeout=10,
                    kwargs={
                        "row_factory": dict_row,
                        "connect_timeout": 10,
                    },
                    open=True,
                )

    # Todos os usos existentes seguem com: with conectar_banco() as conexao:
    # Ao sair do bloco, a conexão volta ao pool em vez de fechar o socket.
    return _pool.connection()


def criar_tabelas():
    """Cria as tabelas do SGE no PostgreSQL, caso ainda não existam."""
    with conectar_banco() as conexao:
        conexao.execute("""
            CREATE TABLE IF NOT EXISTS usuarios (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                nome TEXT NOT NULL,
                email TEXT NOT NULL UNIQUE,
                senha_hash TEXT NOT NULL
            )
        """)

        conexao.execute("""
            CREATE TABLE IF NOT EXISTS progresso_estudos (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                usuario_id INTEGER NOT NULL REFERENCES usuarios(id),
                materia TEXT NOT NULL,
                horas_estudadas DOUBLE PRECISION NOT NULL DEFAULT 0,
                progresso INTEGER NOT NULL DEFAULT 0,
                nivel INTEGER NOT NULL DEFAULT 1,
                UNIQUE (usuario_id, materia)
            )
        """)

        conexao.execute("""
            CREATE TABLE IF NOT EXISTS progresso_aulas (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                usuario_id INTEGER NOT NULL REFERENCES usuarios(id),
                materia TEXT NOT NULL,
                nivel INTEGER NOT NULL DEFAULT 1
                    CHECK (nivel BETWEEN 1 AND 10),
                pagina INTEGER NOT NULL DEFAULT 1
                    CHECK (pagina BETWEEN 1 AND 10),
                paginas_concluidas TEXT NOT NULL DEFAULT '[]',
                segundos_estudados INTEGER NOT NULL DEFAULT 0
                    CHECK (segundos_estudados >= 0),
                atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                UNIQUE (usuario_id, materia)
            )
        """)

        conexao.execute("""
            CREATE TABLE IF NOT EXISTS respostas_quiz (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                usuario_id INTEGER NOT NULL REFERENCES usuarios(id),
                materia TEXT NOT NULL,
                nivel INTEGER NOT NULL CHECK (nivel BETWEEN 1 AND 10),
                questao_id TEXT NOT NULL,
                resposta TEXT NOT NULL,
                acertou INTEGER NOT NULL CHECK (acertou IN (0, 1)),
                respondido_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                UNIQUE (usuario_id, materia, nivel, questao_id)
            )
        """)

        conexao.execute("""
            CREATE TABLE IF NOT EXISTS niveis_curso (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                usuario_id INTEGER NOT NULL REFERENCES usuarios(id),
                materia TEXT NOT NULL,
                nivel INTEGER NOT NULL CHECK (nivel BETWEEN 1 AND 10),
                resumo_concluido INTEGER NOT NULL DEFAULT 0
                    CHECK (resumo_concluido IN (0, 1)),
                aprovado INTEGER NOT NULL DEFAULT 0
                    CHECK (aprovado IN (0, 1)),
                atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                UNIQUE (usuario_id, materia, nivel)
            )
        """)


if __name__ == "__main__":
    criar_tabelas()
    print("Banco de dados PostgreSQL do SGE preparado!")
